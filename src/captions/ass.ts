import type { WordTiming } from "../tts/types.js";

export interface CaptionWord extends WordTiming {
  /** Punctuation after the word in the script ("," "." ...), used to end caption chunks naturally. */
  breakAfter?: string;
}

export interface CaptionStyle {
  width: number;
  height: number;
  font: string;
  fontSize: number;
  textColor: string; // #RRGGBB
  highlightColor: string; // #RRGGBB
  outlineColor: string;
  outline: number;
  shadow: number;
  /** Distance of the caption block's bottom edge from the bottom of the frame (px). */
  marginV: number;
  marginH: number;
  uppercase: boolean;
  maxWordsPerChunk: number;
  maxCharsPerChunk: number;
  /** Show captions slightly before the word is heard (perceived as better sync). */
  leadSec: number;
  /** Pop-in animation for each new chunk. */
  pop: boolean;
}

export interface CaptionChunk {
  words: CaptionWord[];
  start: number;
  end: number;
}

/** "#RRGGBB" → ASS "&H00BBGGRR" (alpha first, then BGR). */
export function hexToAss(hex: string, alpha = 0): string {
  const m = /^#?([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(hex);
  if (!m) throw new Error(`invalid colour ${hex}`);
  const a = alpha.toString(16).padStart(2, "0").toUpperCase();
  return `&H${a}${m[3]!.toUpperCase()}${m[2]!.toUpperCase()}${m[1]!.toUpperCase()}`;
}

/** Inline override colour (`\\c&HBBGGRR&`, no alpha byte, trailing ampersand). */
export function hexToAssInline(hex: string): string {
  return `${hexToAss(hex).replace(/^&H00/, "&H")}&`;
}

/** ASS timestamp H:MM:SS.cc (centiseconds). */
export function assTime(sec: number): string {
  const cs = Math.max(0, Math.round(sec * 100));
  const h = Math.floor(cs / 360000);
  const m = Math.floor((cs % 360000) / 6000);
  const s = Math.floor((cs % 6000) / 100);
  return `${h}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}.${String(cs % 100).padStart(2, "0")}`;
}

export function escapeAss(text: string): string {
  return text.replace(/\\/g, "\\\\").replace(/\{/g, "(").replace(/\}/g, ")").replace(/\n/g, " ");
}

/**
 * Group words into short caption chunks. Words are first split into phrases at punctuation
 * and long silences (a chunk never straddles a comma or a full stop), then each phrase is cut
 * into the fewest, most even chunks that respect the word and character limits — so you get
 * "OCTOPUSES SOLVE / PUZZLES," instead of "OCTOPUSES SOLVE / PUZZLES, USE".
 */
export function chunkWords(words: CaptionWord[], maxWords: number, maxChars: number, maxGapSec = 0.6): CaptionChunk[] {
  const len = (ws: CaptionWord[]) => ws.reduce((a, w) => a + w.text.length, 0) + Math.max(0, ws.length - 1);
  const phrases: CaptionWord[][] = [];
  let cur: CaptionWord[] = [];
  words.forEach((w, i) => {
    const prev = cur[cur.length - 1];
    if (prev && w.start - prev.end > maxGapSec) {
      phrases.push(cur);
      cur = [];
    }
    cur.push(w);
    if (w.breakAfter || i === words.length - 1) {
      phrases.push(cur);
      cur = [];
    }
  });
  if (cur.length) phrases.push(cur);

  const chunks: CaptionWord[][] = [];
  for (const phrase of phrases) {
    for (let k = Math.ceil(phrase.length / maxWords); k <= phrase.length; k++) {
      const split = evenSplit(phrase, k);
      // A single over-long word is allowed to overflow (it will wrap/shrink visually).
      if (split.every((c) => c.length <= maxWords && (len(c) <= maxChars || c.length === 1))) {
        chunks.push(...split);
        break;
      }
    }
  }
  return chunks.map((ws) => ({ words: ws, start: ws[0]!.start, end: ws[ws.length - 1]!.end }));
}

/** Split into k contiguous groups with sizes differing by at most one (larger groups first). */
function evenSplit<T>(items: T[], k: number): T[][] {
  const out: T[][] = [];
  const base = Math.floor(items.length / k);
  let extra = items.length % k;
  let i = 0;
  for (let g = 0; g < k; g++) {
    const size = base + (extra-- > 0 ? 1 : 0);
    out.push(items.slice(i, i + size));
    i += size;
  }
  return out.filter((g) => g.length);
}

export function buildAss(words: CaptionWord[], style: CaptionStyle): string {
  const chunks = chunkWords(words, style.maxWordsPerChunk, style.maxCharsPerChunk);
  const base = hexToAss(style.textColor);
  const hi = hexToAss(style.highlightColor);
  const baseInline = hexToAssInline(style.textColor);
  const hiInline = hexToAssInline(style.highlightColor);
  const header = [
    "[Script Info]",
    "; Generated by ai-video-factory",
    "ScriptType: v4.00+",
    `PlayResX: ${style.width}`,
    `PlayResY: ${style.height}`,
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    "YCbCr Matrix: TV.709",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    `Style: Caption,${style.font},${style.fontSize},${base},${hi},${hexToAss(style.outlineColor)},${hexToAss("#000000", 0x60)},0,0,0,0,100,100,1,0,1,${style.outline},${style.shadow},2,${style.marginH},${style.marginH},${style.marginV},1`,
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
  ];
  const events: string[] = [];
  chunks.forEach((chunk, ci) => {
    const next = chunks[ci + 1];
    const chunkEnd = Math.min(chunk.end + 0.35, next ? next.start - style.leadSec : chunk.end + 0.35);
    chunk.words.forEach((w, wi) => {
      const start = (wi === 0 ? chunk.start : w.start) - style.leadSec;
      const end = wi === chunk.words.length - 1 ? chunkEnd : chunk.words[wi + 1]!.start - style.leadSec;
      if (end - start < 0.01) return;
      const popIn = style.pop && wi === 0;
      const text = chunk.words
        .map((cw, k) => {
          const t = escapeAss(style.uppercase ? cw.text.toUpperCase() : cw.text);
          const active = k === wi;
          const color = `\\c${active ? hiInline : baseInline}`;
          const scale = active ? 108 : 100;
          // Pop-in: every word animates from 80 % to its target scale over 110 ms.
          const tags = popIn
            ? `${color}\\fscx${scale - 22}\\fscy${scale - 22}\\t(0,110,\\fscx${scale}\\fscy${scale})`
            : `${color}\\fscx${scale}\\fscy${scale}`;
          return `{${tags}}${t}`;
        })
        .join(" ");
      events.push(`Dialogue: 0,${assTime(Math.max(0, start))},${assTime(end)},Caption,,0,0,0,,${text}`);
    });
  });
  return [...header, ...events, ""].join("\n");
}
